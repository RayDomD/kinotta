test('Colour settles keyboard edits, resets with nulls, ignores stale stills and plays an ungraded proxy', async ({ page }) => {
  test.setTimeout(60_000);
  await page.goto(server.url);
  await page.getByRole('navigation', { name: 'Reels' }).getByRole('button', { name: /Founder talk/ }).click();
  await page.getByRole('navigation', { name: 'Phase' }).getByRole('button', { name: 'Colour', exact: true }).click();
  const colour = page.getByRole('main', { name: 'Colour', exact: true });
  await colour.locator('.rv-colour-clip').first().click();
  const list = async () => (await (await page.request.get(`${server.url}/api/reels/${SLUG}/edits`)).json()).operations;
  const start = (await list()).length;
  const exposure = colour.getByRole('slider', { name: 'Exposure', exact: true });
  await expect(exposure).toHaveAttribute('aria-valuenow', '0');
  expect((await list()).length).toBe(start);
  await exposure.press('ArrowRight');
  await exposure.press('ArrowRight');
  await exposure.press('ArrowRight');
  expect((await list()).length).toBe(start);
  await expect.poll(async () => (await list()).length).toBe(start + 1);
  expect((await list()).at(-1).changes.grade).toEqual({ exposure: 0.003 });
  await exposure.dblclick();
  await expect.poll(async () => (await list()).length).toBe(start + 2);
  expect((await list()).at(-1).changes.grade).toEqual({ exposure: null });
  await expect(exposure).toHaveAttribute('aria-valuenow', '0');

  let releaseOld: () => void = () => {};
  const held = new Promise<void>((resolve) => { releaseOld = resolve; });
  await page.route('**/placements/first-picture/graded-still?*', async (route) => {
    const grade = new URL(route.request().url()).searchParams.get('grade');
    if (grade && JSON.parse(grade).exposure === 0.5) await held;
    await route.continue();
  });
  const oldRequest = page.waitForRequest((request) => request.url().includes('graded-still') && new URL(request.url()).searchParams.get('grade') === JSON.stringify({ exposure: 0.5 }));
  await colour.getByLabel('Exposure value', { exact: true }).fill('0.5');
  await oldRequest;
  await colour.getByLabel('Exposure value', { exact: true }).fill('0.7');
  await expect(colour.getByAltText('Graded frame')).toHaveAttribute('src', /exposure%22%3A0\.7/);
  releaseOld();
  await page.waitForTimeout(500);
  await expect(colour.getByAltText('Graded frame')).toHaveAttribute('src', /exposure%22%3A0\.7/);
  expect((await list()).length).toBe(start + 3);
  await colour.getByRole('button', { name: 'Reset grade', exact: true }).click();
  await expect.poll(async () => (await list()).length).toBe(start + 4);
  expect((await list()).at(-1).changes.grade).toEqual(Object.fromEntries(Object.keys(GRADE_SPEC).map((key) => [key, null])));
  await expect(exposure).toHaveAttribute('aria-valuenow', '0');
  const response = page.waitForResponse((reply) => reply.url().includes('/placements/first-picture/graded-playback'));
  await colour.getByRole('button', { name: 'Play', exact: true }).click();
  expect((await response).status()).toBe(409);
  await expect(colour.locator('video')).toHaveAttribute('src', /\/media\//);
  await expect.poll(() => colour.locator('video').evaluate((v: HTMLVideoElement) => !v.paused && v.currentTime > 0)).toBe(true);
  await expect(colour.getByText('Grade preview rendering', { exact: true })).toHaveCount(0);
  await colour.getByRole('button', { name: 'Pause', exact: true }).click();
  await expect(colour.getByRole('alert')).toHaveCount(0);
});

for (const destination of ['clip', 'Edit', 'Storyboard', 'version']) {
  test(`Colour saves pending keyboard edits before leaving by ${destination}`, async ({ page }) => {
    await page.goto(server.url);
    await page.getByRole('navigation', { name: 'Reels' }).getByRole('button', { name: /Founder talk/ }).click();
    const phases = page.getByRole('navigation', { name: 'Phase' });
    await phases.getByRole('button', { name: 'Colour', exact: true }).click();
    const colour = page.getByRole('main', { name: 'Colour', exact: true });
    await colour.locator('.rv-colour-clip').first().click();
    const list = async () => (await (await page.request.get(`${server.url}/api/reels/${SLUG}/edits`)).json()).operations;
    const before = await list();
    const exposure = colour.getByRole('slider', { name: 'Exposure', exact: true });
    const value = Number(await exposure.getAttribute('aria-valuenow'));
    if (destination === 'version') {
      const rail = page.getByRole('tab', { name: 'Reel rail', exact: true });
      if (await rail.getAttribute('aria-selected') !== 'true') await rail.click();
    }
    await exposure.press('ArrowRight');
    expect((await list()).length).toBe(before.length);
    if (destination === 'clip') await colour.locator('.rv-colour-clip').nth(1).click();
    else if (destination === 'version') await page.locator('button[data-version="1"]').click();
    else await phases.getByRole('button', { name: destination, exact: true }).click();
    await expect.poll(async () => (await list()).length).toBe(before.length + 1);
    const saved = (await list()).at(-1);
    expect(saved.placement).toBe('first-picture');
    expect(saved.changes.grade).toEqual({ exposure: Number((value + 0.001).toFixed(3)) });
    await page.waitForTimeout(500);
    expect((await list()).length).toBe(before.length + 1);
  });
}

