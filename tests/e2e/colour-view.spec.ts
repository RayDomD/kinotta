test('Colour formats filter labels, signed RGB and fixed numeric fields', async ({ page }) => {
  await run(process.execPath, [resolve('bin/kinotta.mjs'), 'edit', SLUG, '--project', project, '--by', 'colour-agent', JSON.stringify({ kind: 'placement-change', placement: 'first-picture', changes: { grade: { shadowsColor: [-0.2, 0.31, -0.11], temperature: 10000, tint: -0.18, contrast: 1.82, blacks: -0.015, whites: 0, mids: 0, exposure: 0 } } })]);
  await page.goto(server.url);
  await page.getByRole('navigation', { name: 'Reels' }).getByRole('button', { name: /Founder talk/ }).click();
  await page.getByRole('navigation', { name: 'Phase' }).getByRole('button', { name: 'Colour', exact: true }).click();
  const colour = page.getByRole('main', { name: 'Colour', exact: true });
  await colour.locator('.rv-colour-clip').first().click();
  await expect(colour.getByRole('heading', { name: 'Lift colorbalance rs gs bs', exact: true })).toBeVisible();
  await expect(colour.getByRole('heading', { name: 'Gamma colorbalance rm gm bm', exact: true })).toBeVisible();
  await expect(colour.getByRole('heading', { name: 'Gain colorbalance rh gh bh', exact: true })).toBeVisible();
  await expect(colour.getByRole('heading', { name: 'Global exposure \u00b7 colortemperature \u00b7 eq', exact: true })).toBeVisible();
  await expect(colour.getByLabel('Lift RGB')).toHaveText('-0.20 +0.31 -0.11');
  await expect(colour.getByLabel('Gain RGB')).toHaveText('+0.00 +0.00 +0.00');
  for (const [label, value] of [['Exposure', '0.00'], ['Temperature', '10000'], ['Tint', '-0.18'], ['Contrast', '1.82'], ['Black', '-0.015'], ['White', '0.000'], ['Mid', '0.00']]) {
    await expect(colour.getByLabel(`${label} value`, { exact: true })).toHaveValue(value);
  }
  const contrast = colour.getByLabel('Contrast value', { exact: true });
  await contrast.fill('1.65');
  await contrast.blur();
  await expect(contrast).toHaveValue('1.65');
  await expect.poll(async () => Number(await colour.getByRole('slider', { name: 'Contrast', exact: true }).getAttribute('aria-valuenow'))).toBeCloseTo(1.65, 12);
});
