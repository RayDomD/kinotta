import { chromium } from 'playwright';
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { expect, it } from 'vitest';
import { startServer } from '../../server/main.ts';
import { copyFixture } from '../helpers/project.ts';
import { invariants as transportChecks } from '../../web/src/review/_internal/Transport.verify.ts';
import { invariants as dividerChecks } from '../../web/src/review/_internal/ViewerDivider.verify.ts';

it('shares a keyboard scrubber, persists the viewer divider, and restores focus view', { timeout: 90_000 }, async () => {
  const server = await startServer({ projectDir: copyFixture('showreel-project'), port: 0 });
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    await page.addInitScript(() => localStorage.setItem('kinotta.editor.settings', JSON.stringify({ keys: { fit: 'F', rail: 'M' } })));
    await page.goto(server.url);
    await page.getByRole('navigation', { name: 'Reels' }).getByRole('button', { name: 'Product showreel' }).click();
    await page.getByRole('button', { name: 'Review', exact: true }).click();
    const slider = page.getByRole('slider', { name: 'Scrub reel' });
    await slider.waitFor();
    const transport = page.locator('[data-verify-unit="Transport"]');
    expect(await transport.evaluate((root, checks) => checks.map((check) => Boolean((0, eval)(`(${check})`)(root))), transportChecks.map((check) => check.check.toString()))).toEqual(transportChecks.map(() => true));
    await slider.focus();
    await page.keyboard.press('ArrowRight');
    await expect.poll(async () => Number(await slider.getAttribute('aria-valuenow'))).toBeCloseTo(1 / 30);
    await page.getByRole('button', { name: 'Next shot', exact: true }).click();
    expect(Number(await slider.getAttribute('aria-valuenow'))).toBeGreaterThan(1);
    const divider = page.getByRole('separator', { name: 'Picture and tracks' });
    expect(await divider.evaluate((root, checks) => checks.map((check) => Boolean((0, eval)(`(${check})`)(root))), dividerChecks.map((check) => check.check.toString()))).toEqual(dividerChecks.map(() => true));
    await divider.focus();
    await page.keyboard.press('ArrowUp');
    expect(await divider.getAttribute('aria-valuenow')).toBe('60');
    const split = (await divider.boundingBox())!;
    const mainHeight = await divider.evaluate((element) => element.parentElement!.clientHeight);
    await page.mouse.move(split.x + split.width / 2, split.y + split.height / 2); await page.mouse.down();
    await page.mouse.move(split.x + split.width / 2, split.y + split.height / 2 + mainHeight * 0.1, { steps: 5 }); await page.mouse.up();
    expect(await divider.getAttribute('aria-valuenow')).toBe('70');
    await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown');
    expect(await divider.getAttribute('aria-valuenow')).toBe('60');
    await page.evaluate(() => (document.activeElement as HTMLElement).blur());
    await page.keyboard.press('f');
    expect(await page.locator('[data-review-shell="true"]').getAttribute('data-focus')).toBe('true');
    expect(await page.getByRole('region', { name: 'Media timeline' }).isVisible()).toBe(false);
    await page.keyboard.press('Escape');
    expect(await page.locator('[data-review-shell="true"]').getAttribute('data-focus')).toBe('false');
    expect(await divider.getAttribute('aria-valuenow')).toBe('60');
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('kinotta.editor.settings')!));
    expect(saved.keys).toMatchObject({ fit: 'Shift+F', focus: 'F', rail: 'R', marker: 'M' });
    expect(saved.viewerShare).toBe(0.6);
    await page.keyboard.press('?');
    await page.getByRole('dialog', { name: 'Keyboard shortcuts' }).waitFor();
    await page.keyboard.press('Escape');
    expect(await page.getByRole('dialog', { name: 'Keyboard shortcuts' }).isVisible()).toBe(false);
  } finally { await browser.close(); await server.close(); }
});

it('saves and edits markers, closes a sound gap in one undo, appends prompt chips and keeps the frame visible', { timeout: 120_000 }, async () => {
  const dir = copyFixture('showreel-project');
  const sound = join(dir, 'sound.wav');
  expect(spawnSync('ffmpeg', ['-v', 'error', '-y', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=2', sound]).status).toBe(0);
  const server = await startServer({ projectDir: dir, port: 0 });
  const entry = await server.project.referenceMedia('sound.wav');
  await server.project.addOperation('product-showreel', { kind: 'track-add', track: { id: 'music', name: 'Music', order: 0, gain: 1, mute: false } });
  await server.project.addOperation('product-showreel', { kind: 'placement-add', source: { id: entry.id, kind: 'audio', path: '../../../sound.wav', duration: 2 }, placement: { id: 'a', role: 'audio', source: entry.id, track: 'music', at: 1, in: 0, out: 2 } });
  await server.project.addOperation('product-showreel', { kind: 'placement-add', placement: { id: 'b', role: 'audio', source: entry.id, track: 'music', at: 5, in: 0, out: 2 } });
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    await page.goto(server.url);
    await page.getByRole('navigation', { name: 'Reels' }).getByRole('button', { name: 'Product showreel' }).click();
    await page.getByRole('button', { name: 'Review', exact: true }).click();
    await page.locator('[data-verify-unit="MediaEditor"]').waitFor();
    const slider = page.getByRole('slider', { name: 'Scrub reel' });
    await page.getByLabel('Playhead', { exact: true }).fill('4');
    await page.evaluate(() => (document.activeElement as HTMLElement).blur());
    await page.keyboard.press('m');
    await page.getByRole('region', { name: 'Marker settings' }).waitFor();
    await page.getByLabel('Marker name', { exact: true }).fill('Reveal');
    await page.getByRole('button', { name: 'Close marker', exact: true }).click();
    await expect.poll(async () => (await server.project.listMarkers('product-showreel'))[0]?.name).toBe('Reveal');
    await expect.poll(() => page.locator('.rv-scrubber').getByRole('button', { name: 'Marker Reveal', exact: true }).count()).toBe(1);
    await expect.poll(() => page.getByLabel('Timeline ruler', { exact: true }).getByRole('button', { name: 'Marker Reveal', exact: true }).count()).toBe(1);
    const lanes = page.getByRole('region', { name: 'Media timeline' });
    await lanes.locator('[data-placement="a"]').click({ button: 'right' });
    await page.getByRole('menuitem', { name: /^Remove and close the gap/ }).click();
    await expect.poll(async () => (await server.project.readEditList('product-showreel')).operations.at(-1)?.kind).toBe('placement-ripple-remove');
    await expect.poll(() => lanes.locator('[data-placement="b"]').getAttribute('aria-label')).toContain('3.00 to 5.00');
    await page.evaluate(() => (document.activeElement as HTMLElement).blur());
    await page.keyboard.press('Control+z');
    await expect.poll(() => lanes.locator('[data-placement="b"]').getAttribute('aria-label')).toContain('5.00 to 7.00');
    const clip = lanes.locator('[data-placement="b"]'); await clip.scrollIntoViewIfNeeded();
    const box = (await clip.boundingBox())!; const laneWidth = await clip.evaluate((el) => el.closest('.native-lane-bars')!.getBoundingClientRect().width);
    await page.mouse.move(box.x + box.width - 30, box.y + box.height / 2); await page.mouse.down();
    await page.mouse.move(box.x + box.width - 30 - laneWidth / 15, box.y + box.height / 2, { steps: 8 });
    expect(await lanes.locator('.native-snap-line').count()).toBeGreaterThan(0);
    await page.mouse.up();
    await expect.poll(() => clip.getAttribute('aria-label')).toContain('4.00 to 6.00');
    await page.evaluate(() => (document.activeElement as HTMLElement).blur()); await page.keyboard.press('Control+z');
    await expect.poll(() => clip.getAttribute('aria-label')).toContain('5.00 to 7.00');
    await page.getByRole('button', { name: 'Focus picture', exact: true }).click();
    await page.evaluate(() => (document.activeElement as HTMLElement).blur()); await page.keyboard.press('p');
    await page.locator('.rv-frame').click({ position: { x: 120, y: 100 } });
    await page.getByRole('form', { name: 'New review pin' }).waitFor();
    await page.getByLabel('Pin comment', { exact: true }).fill('Focus pin');
    await page.getByRole('button', { name: 'Save pin', exact: true }).click();
    await expect.poll(async () => (await server.project.listComments('product-showreel', 2)).some((comment) => comment.text === 'Focus pin')).toBe(true);
    await page.getByRole('button', { name: 'Leave focus', exact: true }).click();
    await page.getByRole('tab', { name: 'Sound', exact: true }).click();
    const prompt = page.getByLabel('Sound prompt', { exact: true });
    await prompt.fill('A rise under the reveal');
    await page.getByRole('group', { name: 'Mood suggestions' }).getByRole('button', { name: 'Warm', exact: true }).click();
    expect(await prompt.inputValue()).toBe('A rise under the reveal, warm');
    await page.getByRole('group', { name: 'Mood suggestions' }).getByRole('button', { name: 'Warm', exact: true }).click();
    expect(await prompt.inputValue()).toBe('A rise under the reveal, warm');
    await page.getByRole('tab', { name: /^Edits/ }).click();
    await expect.poll(() => page.locator('.native-shot-still iframe').count()).toBeGreaterThan(0);
    const dimensions = await page.evaluate(() => { const main = document.querySelector('main[aria-label="Review"]')!.getBoundingClientRect(); const frame = document.querySelector('.rv-frame')!.getBoundingClientRect(); return { main: main.height, frame: frame.height }; });
    expect(dimensions.frame).toBeGreaterThanOrEqual(dimensions.main * 0.55 - 4);
    const screenshots = resolve('docs/session-summaries/2026-10-15-viewer-transport-clips'); mkdirSync(screenshots, { recursive: true });
    await page.screenshot({ path: join(screenshots, 'dark-1440.png') });
    const measurements = [];
    for (const theme of ['dark', 'light']) {
      await page.getByRole('button', { name: 'Settings', exact: true }).click();
      await page.getByRole('button', { name: 'Appearance', exact: true }).click();
      await page.getByLabel('Theme', { exact: true }).selectOption(theme);
      await page.getByRole('button', { name: 'Close Settings' }).click();
      for (const width of [390, 768, 1024, 1272, 1600]) {
        await page.setViewportSize({ width, height: 900 });
        const measurement = await page.evaluate(() => { const root = document.documentElement; return { width: root.clientWidth, content: root.scrollWidth, frame: document.querySelector('.rv-frame')!.getBoundingClientRect().height }; });
        expect(measurement.content).toBeLessThanOrEqual(measurement.width);
        expect(measurement.frame).toBeGreaterThan(40);
        measurements.push({ theme, ...measurement });
      }
    }
    writeFileSync(join(screenshots, 'measurements.json'), JSON.stringify(measurements, null, 2));
    await page.screenshot({ path: join(screenshots, 'light-1600.png') });
    await page.reload(); await slider.waitFor();
    await expect.poll(() => page.locator('.rv-scrubber').getByRole('button', { name: 'Marker Reveal', exact: true }).count()).toBe(1);
    await page.locator('.rv-scrubber').getByRole('button', { name: 'Marker Reveal', exact: true }).click();
    await page.getByRole('button', { name: 'Remove marker', exact: true }).click();
    await expect.poll(() => server.project.listMarkers('product-showreel')).toEqual([]);
  } finally { await browser.close(); await server.close(); }
});
