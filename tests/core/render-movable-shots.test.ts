import { chromium } from 'playwright';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';
import { expect, it } from 'vitest';
import { startServer } from '../../server/main.ts';
import { copyFixture } from '../helpers/project.ts';
import { invariants } from '../../web/src/review/_internal/EditorialLanes.verify.ts';

it('drags code shots with live preview, separates overlaps, trims, extends and saves the picture', { timeout: 90_000 }, async () => {
  const dir = copyFixture('showreel-project');
  const server = await startServer({ projectDir: dir, port: 0 });
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    await page.goto(server.url);
    await page.getByRole('navigation', { name: 'Reels' }).getByRole('button', { name: /Product showreel/ }).click();
    await page.getByRole('button', { name: 'Review', exact: true }).click();
    const lanes = page.locator('[data-verify-unit="EditorialLanes"]');
    const cube = lanes.locator('[data-graphic="cube-lands"]');
    await expect.poll(() => cube.count()).toBe(1);
    await expect.poll(() => cube.locator('.native-trim-end').count()).toBe(1);
    expect(await cube.textContent()).toContain('Cube lands');
    const scene = page.frameLocator('iframe[title="Authored graphics"]').locator('[data-scene="cube-lands"]');
    const clock = page.getByLabel('Playhead', { exact: true });
    await cube.scrollIntoViewIfNeeded();
    const width = (await lanes.locator('[data-row="graphics"] .native-lane-bars').boundingBox())!.width;
    const box = (await cube.boundingBox())!;
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width / 2 + width * 2 / 15, box.y + box.height / 2, { steps: 5 });
    await expect.poll(async () => Number(await scene.getAttribute('data-start'))).toBeCloseTo(2, 2);
    await page.mouse.up();
    await expect.poll(async () => (await server.project.readEditList('product-showreel')).operations.at(-1)).toMatchObject({ kind: 'clip-slide', clip: 'cube-lands' });
    const logo = (await lanes.locator('[data-graphic="logo-lockup"]').boundingBox())!;
    const moved = (await cube.boundingBox())!;
    expect(moved.y >= logo.y + logo.height || logo.y >= moved.y + moved.height).toBe(true);
    await clock.fill('0');
    expect(await scene.evaluate((el) => el.classList.contains('active'))).toBe(false);
    await clock.fill('2.2');
    await expect.poll(() => scene.evaluate((el) => el.classList.contains('active'))).toBe(true);
    const edge = (await cube.locator('.native-trim-end').boundingBox())!;
    await page.mouse.move(edge.x + edge.width / 2, edge.y + edge.height / 2);
    await page.mouse.down();
    await page.mouse.move(edge.x + edge.width / 2 - width * 0.8 / 15, edge.y + edge.height / 2, { steps: 5 });
    await page.mouse.up();
    await expect.poll(() => scene.getAttribute('data-duration')).toBe('1');
    // Drag a shot beyond the current end. The expanding window must keep the gesture's original scale.
    const cta = lanes.locator('[data-graphic="cta"]');
    await cta.scrollIntoViewIfNeeded();
    await expect.poll(() => cta.locator('.native-trim-end').count()).toBe(1);
    const ctaBox = (await cta.boundingBox())!;
    const ctaX = ctaBox.x + ctaBox.width / 4;
    await page.mouse.move(ctaX, ctaBox.y + ctaBox.height / 2);
    await page.mouse.down();
    await page.mouse.move(ctaX + width * 2 / 15, ctaBox.y + ctaBox.height / 2, { steps: 5 });
    await expect.poll(async () => Number(await page.getByLabel('Playhead', { exact: true }).getAttribute('max'))).toBeCloseTo(17, 4);
    await page.mouse.move(ctaX + width * 3 / 15, ctaBox.y + ctaBox.height / 2, { steps: 5 });
    await page.mouse.up();
    await expect.poll(async () => Number(await page.getByLabel('Playhead', { exact: true }).getAttribute('max'))).toBeCloseTo(18, 4);
    await server.project.addOperation('product-showreel', { kind: 'clip-slide', clip: 'cta', delta: 19 - Number(await clock.getAttribute('max')) });
    await page.reload();
    await expect.poll(() => page.frameLocator('iframe[title="Authored graphics"]').locator('[data-scene="cta"]').getAttribute('data-start')).toBe('16.2');
    await expect.poll(() => page.getByLabel('Playhead', { exact: true }).getAttribute('max')).toBe('19');
    expect(await page.frameLocator('iframe[title="Authored graphics"]').locator('body').evaluate(() => (window as unknown as { DURATION: number }).DURATION)).toBe(19);
    for (const invariant of invariants) expect(await lanes.evaluate(invariant.check), invariant.description).toBe(true);
    expect(await server.project.freezeEdits('product-showreel')).toEqual({ version: 3 });
    await expect.poll(async () => (await server.project.readVersion('product-showreel', 3)).duration).toBe(19);
    await page.reload();
    await expect.poll(() => page.frameLocator('iframe[title="Authored graphics"]').locator('[data-scene="cta"]').getAttribute('data-start')).toBe('16.2');
    expect(await page.frameLocator('iframe[title="Authored graphics"]').locator('body').evaluate(() => (window as unknown as { DURATION: number }).DURATION)).toBe(19);
    await page.getByLabel('Playhead', { exact: true }).fill('17');
    await expect.poll(() => page.frameLocator('iframe[title="Authored graphics"]').locator('[data-scene="cta"]').evaluate((el) => el.classList.contains('active'))).toBe(true);
    const queued = await server.project.render({ reel: 'product-showreel', version: 3, preset: 'draft' });
    const rendered = await server.project.whenRendered(queued.id);
    expect(rendered.state, rendered.error).toBe('done');
    const probe = spawnSync('ffprobe', ['-v', 'error', '-count_frames', '-select_streams', 'v:0', '-show_entries', 'stream=nb_read_frames', '-of', 'json', join(dir, rendered.output!)], { encoding: 'utf8' });
    expect(probe.status, probe.stderr).toBe(0);
    expect(JSON.parse(probe.stdout).streams[0].nb_read_frames).toBe('570');
  } finally {
    await browser.close();
    await server.close();
  }
});
